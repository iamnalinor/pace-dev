import { writeFileSync } from "node:fs";

import {
  color,
  COLOR_ROLES,
  type ColorRole,
  font,
  layout,
  radius,
  size,
  space,
  type ThemeName,
  THEMES,
  TYPE_ROLES,
  type TypeRole,
  typeRole,
  type TypeStyle,
} from "@pace/core";

import { LAYOUT_CLASSES } from "./layout-classes.ts";
import { committed, pageFiles, ROOT } from "./page-files.ts";

/**
Generates the app's platform values from the design tokens (`packages/core/src/design/tokens.json`,
spec §3): the Tailwind theme (`tailwind-theme.json`, read by `apps/app/tailwind.config.js`), the
per-theme `--pace-*` CSS variables (NativeWind `vars()`, `apps/app/src/ui/generated/tokens.ts`); both
are committed. `GENERATED_CLASSES` is the list of classes the lint rule `pace/no-raw-design-values`
accepts (eslint.config.ts passes it as `allowedClasses`).

  bun design:generate            write the files
  bun design:generate --check    fail when a committed file is stale (run by `bun lint`)

Class names: colours drop `bg.`/`status.` and `.default`, dots and camel case become dashes
(`bg-app`, `text-label-secondary`, `bg-fill-3`, `text-danger`, `bg-hue-blue-tint`); type roles keep
their names (`text-body`, `text-largeTitle`, `text-numeric-live`) and switch to their desktop column
at `lg` (≥ 1024) on their own; spacing keeps Tailwind's px-faithful keys restricted to `space`
(`p-4` = 16); widths and heights add the size and layout tokens (`h-hit-web`, `min-h-row`,
`w-sidebar`); radius is `rounded-xs … rounded-pill`.
*/

export const GENERATED_TS = "apps/app/src/ui/generated/tokens.ts";
export const GENERATED_THEME = "apps/app/src/ui/generated/tailwind-theme.json";

const HEADER =
  "Generated by scripts/design/generate-design.ts from packages/core/src/design/tokens.json.\nDo not edit: run `bun design:generate`.";

const px = (value: number): string => `${value}px`;

const kebab = (text: string): string =>
  text.replaceAll(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);

/** `bg.app` → `app`, `label.secondary` → `label-secondary`, `status.danger` → `danger`. */
export const colorClassName = (role: ColorRole): string =>
  kebab(role.replace(/^(?:bg|status)\./, "").replace(/\.default$/, "")).replaceAll(".", "-");

/** `body` → `body`, `numeric.live` → `numeric-live`. */
export const typeClassName = (role: TypeRole): string => role.replaceAll(".", "-");

/** The `--pace-<colour>` variables of one theme. */
export const themeVars = (theme: ThemeName): Readonly<Record<string, string>> =>
  Object.fromEntries(
    COLOR_ROLES.map((role) => [`--pace-${colorClassName(role)}`, color(theme, role)]),
  );

/** Tailwind's 4-px key of a px value: 16 → `4`, 2 → `0.5`. */
const spaceKey = (value: number): string => String(value / 4);

// Container sizes beyond `space` that the app's layout needs (multiples of 16, px-faithful keys).
const CONTAINER_SIZES = [80, 96, 128];

const SIZE_TOKENS: Readonly<Record<string, number>> = {
  "auth-card": size.authCard,
  "chip-max": size.chip.max,
  content: layout.contentMax,
  "content-wide": layout.contentMaxWide,
  dialog: layout.dialog,
  hit: size.hit,
  "hit-web": size.hitWeb,
  "icon-bar": size.icon.bar,
  "icon-control": size.icon.control,
  "icon-inline": size.icon.inline,
  inspector: layout.inspectorWidth,
  "inspector-max": layout.inspectorMax,
  "inspector-min": layout.inspectorMin,
  message: size.message,
  "narrow-column": size.narrowColumn,
  "nav-bar": layout.navBar,
  popover: layout.popover,
  "popover-max": layout.popoverMax,
  "popover-min": layout.popoverMin,
  rail: layout.rail,
  row: size.row.min,
  "row-compact": size.row.compact,
  sidebar: layout.sidebarWidth,
  // The sidebar's column inside its `px-3` (a toast docked at its foot).
  "sidebar-inner": layout.sidebarWidth - 2 * space["4"],
  "toast-max": size.toast.max,
  "tooltip-max": size.tooltip.max,
};

const WEIGHT_NAMES: Readonly<Record<number, string>> = {
  400: "normal",
  500: "medium",
  600: "semibold",
  700: "bold",
};

type FontSizeEntry = readonly [
  string,
  { fontWeight: string; letterSpacing?: string; lineHeight: string },
];
// No weight: a role's weight is the same in both columns, and a desktop rule that set it would
// override an explicit `font-*` class (it comes later in the CSS).
type DesktopType = { fontSize: string; letterSpacing: string; lineHeight: string };

export type TailwindTheme = {
  borderRadius: Record<string, string>;
  borderWidth: Record<string, string>;
  colors: Record<string, string>;
  flex: Record<string, string>;
  fontFamily: Record<string, readonly string[]>;
  fontSize: Record<string, FontSizeEntry>;
  fontWeight: Record<string, string>;
  screens: Record<string, string>;
  size: Record<string, string>;
  spacing: Record<string, string>;
  /** Each type role's desktop column, applied from `screens.lg` by the config's plugin. */
  typeDesktop: Record<string, DesktopType>;
};

// Tracking is stored in em; the phone gets px (NativeWind does not resolve em letter spacing).
const tracking = (style: TypeStyle): string =>
  px(Math.round(style.tracking * style.size * 100) / 100);

const fontSizeEntry = (style: TypeStyle): FontSizeEntry => [
  px(style.size),
  {
    fontWeight: String(style.weight),
    ...(style.tracking !== 0 && { letterSpacing: tracking(style) }),
    lineHeight: px(style.line),
  },
];

const desktopType = (style: TypeStyle): DesktopType => ({
  fontSize: px(style.size),
  letterSpacing: tracking(style),
  lineHeight: px(style.line),
});

const sizeScale = (): Record<string, string> => {
  const numeric = [...Object.values(space), ...CONTAINER_SIZES].map(
    (value) => [spaceKey(value), px(value)] as const,
  );
  const named = Object.entries(SIZE_TOKENS).map(([name, value]) => [name, px(value)] as const);
  return Object.fromEntries([
    ...numeric,
    ...named,
    ["1/2", "50%"],
    ["2/5", "40%"],
    ["full", "100%"],
    ["auto", "auto"],
  ]);
};

type Pair = readonly [string, string];

const record = (pairs: readonly Pair[]): Record<string, string> => Object.fromEntries(pairs);

export const tailwindTheme = (): TailwindTheme => ({
  borderRadius: record([
    ["none", "0px"],
    ...Object.entries(radius).map(([name, value]): Pair => [name, px(value)]),
  ]),
  borderWidth: { stroke: px(size.stroke) },
  colors: record([
    ...COLOR_ROLES.map((role): Pair => {
      const name = colorClassName(role);
      return [name, `var(--pace-${name})`];
    }),
    ["transparent", "transparent"],
  ]),
  flex: { "2": "2 2 0%", "3": "3 3 0%" },
  fontFamily: { sans: [font.sans, "system-ui", "sans-serif"] },
  fontSize: Object.fromEntries(
    TYPE_ROLES.map((role) => [typeClassName(role), fontSizeEntry(typeRole(role, "phone"))]),
  ),
  fontWeight: Object.fromEntries(
    font.weights.map((weight) => [WEIGHT_NAMES[weight] ?? String(weight), String(weight)]),
  ),
  screens: { lg: px(layout.breakpoint.expanded), md: px(layout.breakpoint.medium) },
  size: sizeScale(),
  spacing: Object.fromEntries(Object.values(space).map((value) => [spaceKey(value), px(value)])),
  typeDesktop: Object.fromEntries(
    TYPE_ROLES.map((role) => [typeClassName(role), desktopType(typeRole(role, "desktop"))]),
  ),
});

const COLOR_PREFIXES = ["bg", "text", "border"];
const SPACE_PREFIXES = ["p", "px", "py", "pt", "pr", "pb", "pl", "gap", "gap-x", "gap-y"];
const OFFSET_PREFIXES = [
  "m",
  "mx",
  "my",
  "mt",
  "mr",
  "mb",
  "ml",
  "inset",
  "inset-x",
  "inset-y",
  "top",
  "right",
  "bottom",
  "left",
];
const SIZE_PREFIXES = ["h", "w", "min-h", "min-w", "max-h", "max-w", "size"];
const RADIUS_PREFIXES = ["rounded", "rounded-t", "rounded-b", "rounded-l", "rounded-r"];

const cross = (prefixes: readonly string[], keys: readonly string[]): string[] =>
  prefixes.flatMap((prefix) => keys.map((key) => `${prefix}-${key}`));

/** Every class the lint rule accepts, sorted. */
export const generatedClasses = (): readonly string[] => {
  const theme = tailwindTheme();
  const spacing = Object.keys(theme.spacing);
  const offsets = cross(OFFSET_PREFIXES, spacing);
  const negative = offsets.filter((name) => !name.endsWith("-0")).map((name) => `-${name}`);
  const all = new Set([
    ...cross(COLOR_PREFIXES, Object.keys(theme.colors)),
    ...Object.keys(theme.fontSize).map((name) => `text-${name}`),
    ...cross(SPACE_PREFIXES, spacing),
    ...offsets,
    ...negative,
    ...cross(SIZE_PREFIXES, Object.keys(theme.size)),
    ...cross(RADIUS_PREFIXES, Object.keys(theme.borderRadius)),
    ...LAYOUT_CLASSES,
  ]);
  return [...all].toSorted((a, b) => a.localeCompare(b));
};

/** The list `pace/no-raw-design-values` gets as `allowedClasses` (eslint.config.ts). */
export const GENERATED_CLASSES: readonly string[] = generatedClasses();

const literal = (value: string): string => JSON.stringify(value);

const objectLines = (entries: Readonly<Record<string, string>>, indent: string): string =>
  Object.entries(entries)
    .toSorted(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `${indent}${literal(key)}: ${literal(value)},`)
    .join("\n");

const tokensModule = (): string => {
  const comment = HEADER.split("\n")
    .map((line) => `// ${line}`)
    .join("\n");
  const themes = THEMES.map(
    (theme) => `  ${theme}: {\n${objectLines(themeVars(theme), " ".repeat(4))}\n  },`,
  ).join("\n");
  return `${comment}

/** The \`--pace-<colour>\` CSS variables of each theme, set on the root view with NativeWind \`vars()\`. */
export const THEME_VARS = {
${themes}
} as const;
`;
};

const themeJson = (): string =>
  `${JSON.stringify({ $comment: HEADER.replace("\n", " "), ...tailwindTheme() }, null, 2)}\n`;

/** Path (from the repo root) → content of every generated file. */
export const generateDesign = (): Readonly<Record<string, string>> => ({
  ...pageFiles(committed),
  [GENERATED_THEME]: themeJson(),
  [GENERATED_TS]: tokensModule(),
});

const readCommitted = (path: string): string | undefined => {
  try {
    return committed(path);
  } catch {
    return undefined;
  }
};

if (import.meta.main) {
  const isCheck = process.argv.includes("--check");
  const stale = Object.entries(generateDesign()).filter(
    ([path, content]) => readCommitted(path) !== content,
  );
  if (isCheck) {
    if (stale.length > 0) {
      console.error(
        `Stale generated design files (run \`bun design:generate\`): ${stale.map(([path]) => path).join(", ")}`,
      );
      process.exit(1);
    }
  } else {
    for (const [path, content] of stale) {
      writeFileSync(new URL(path, ROOT), content);
      console.log(`wrote ${path}`);
    }
  }
}
